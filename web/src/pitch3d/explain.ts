import type { Clip, Roster, Shot } from "../types";
import type { Spot } from "./overlays";

/** What the Live tab hands the 3D pitch to explain one shot. */
export interface ExplainRequest {
  key: string;
  title: string; // the moment's kind label, e.g. "Goal" or "Big chance"
  shot: Shot;
  clip: Clip;
}

export interface Caption {
  kind: string;
  text: string;
  color: string;
}

export type Draw =
  | { type: "arrow"; a: Spot; b: Spot; color: string; width: number; opacity: number }
  | { type: "line"; a: Spot; b: Spot; color: string; width: number; opacity: number }
  | { type: "ring"; at: Spot; color: string; radius: number }
  | { type: "wedge"; apex: Spot; a: Spot; b: Spot; color: string };

export interface Beat {
  t: number; // match time in seconds
  caption?: Caption;
  draw?: Draw[];
  rate?: number; // playback speed from here on
  cam?: "shooter";
  strike?: boolean; // the ball is struck: draw its flight
}

export interface Script {
  start: number;
  end: number;
  beats: Beat[];
  goalEnd: 1 | -1; // which end the shot was aimed at, in world X sign
  tags: string[]; // players who get a name tag during the replay
}

const BEFORE_S = 8;
const AFTER_S = 3;
const SLOW_FROM_S = 1.0;
const GOAL_POSTS: [number, number] = [30.34, 37.66];

const OUTCOME: Record<string, string> = {
  goal: "Goal.",
  saved: "Saved by the keeper.",
  off_target: "Off target.",
  blocked: "Blocked.",
};

const pct = (p: number) => Math.round(p * 100);

/**
 * The telestrated replay of one shot, as timed beats. Every number and name in a caption is filled
 * here from the engine's shot record and roster. Nothing is generated by a model.
 */
export function buildScript(req: ExplainRequest, roster: Roster, signal: string): Script | null {
  const { shot, clip } = req;
  const frames = clip.frames;
  if (frames.length < 2) return null;
  const start = Math.max(frames[0].t, shot.t - BEFORE_S);
  const end = Math.min(frames[frames.length - 1].t, shot.t + AFTER_S);
  const club = roster.clubs[shot.team];
  const name = (id: string | null | undefined) => (id ? roster.players[id]?.name ?? id : "");
  const shooter = name(shot.player);
  const goalX = shot.team === "home" ? 105 : 0; // home always attacks toward x = 105 (engine/pitch.py)
  const beats: Beat[] = [];

  beats.push({
    t: start,
    rate: 1,
    caption: { kind: `Replay · ${shot.minute}'`, text: `${req.title} for ${club.name}. Watch how ${shooter} got the chance.`, color: club.primary },
  });

  // The build-up: each pass by the attacking side as it is played.
  const passes = clip.events.filter((e) => e.type === "pass" && e.team === shot.team && e.t >= start && e.t <= shot.t && e.end_x !== null && e.end_y !== null);
  for (const e of passes) {
    const ok = e.outcome === "complete";
    beats.push({
      t: e.t,
      draw: [{ type: "arrow", a: { x: e.x, y: e.y }, b: { x: e.end_x!, y: e.end_y! }, color: ok ? club.primary : "#f4f4f1", width: ok ? 0.32 : 0.18, opacity: ok ? 0.85 : 0.4 }],
    });
  }
  const assist = [...passes].reverse().find((e) => e.player === shot.creator);
  if (shot.creator && assist) {
    beats.push({
      t: assist.t,
      caption: { kind: "The pass", text: `${name(shot.creator)} picks out ${shooter}.`, color: club.primary },
      draw: [{ type: "ring", at: shot.creator, color: "#f4f4f1", radius: 2.4 }],
    });
  }

  // The moment of the shot, slowed down: where it was taken from and who was close.
  const setUp: Draw[] = [
    { type: "wedge", apex: shot.player, a: { x: goalX, y: GOAL_POSTS[0] }, b: { x: goalX, y: GOAL_POSTS[1] }, color: signal },
    { type: "ring", at: shot.player, color: signal, radius: 2.6 },
  ];
  let defence = "";
  if (shot.defender && shot.defender_m !== null) {
    setUp.push({ type: "ring", at: shot.defender, color: "#f4f4f1", radius: 2.4 });
    setUp.push({ type: "line", a: shot.player, b: shot.defender, color: "#f4f4f1", width: 0.14, opacity: 0.7 });
    defence = ` Nearest defender ${name(shot.defender)} is ${shot.defender_m.toFixed(1)} m away.`;
  }
  beats.push({
    t: Math.max(start, shot.t - SLOW_FROM_S),
    rate: 0.3,
    cam: "shooter",
    draw: setUp,
    caption: {
      kind: "The shot",
      text: `${shooter} shoots from ${shot.distance_m.toFixed(1)} m, with ${Math.round(shot.angle_deg)} degrees of goal to aim at.${defence}`,
      color: club.primary,
    },
  });
  beats.push({
    t: shot.t,
    rate: 0.45,
    strike: true,
    caption: {
      kind: `xG ${shot.xg.toFixed(2)}`,
      text: `A chance like this is scored about ${pct(shot.xg)} times in 100.`,
      color: club.primary,
    },
  });

  const goal = shot.outcome === "goal";
  const [h, a] = shot.score_before.split("-").map(Number);
  const after = goal ? (shot.team === "home" ? `${h + 1}-${a}` : `${h}-${a + 1}`) : shot.score_before;
  const [ifGoal, ifMiss] = [pct(shot.wp_if_goal), pct(shot.wp_if_miss)];
  let swing: string;
  if (goal) {
    swing = ifGoal === ifMiss
      ? ` Win probability for ${club.name}: ${ifGoal}%, the same as if it had missed.`
      : ` Win probability for ${club.name} rises to ${ifGoal}%, from ${ifMiss}% had it missed.`;
  } else {
    swing = ifGoal === ifMiss
      ? ` Win probability for ${club.name} stays at ${ifMiss}%. A goal would have moved it by less than one point.`
      : ` A goal would have lifted ${club.name}'s win probability to ${ifGoal}%. It stays at ${ifMiss}%.`;
  }
  beats.push({
    t: Math.min(end, shot.t + 0.9),
    rate: 1,
    caption: {
      kind: goal ? `Goal · ${roster.clubs.home.short} ${after.replace("-", " : ")} ${roster.clubs.away.short}` : "Outcome",
      text: `${OUTCOME[shot.outcome] ?? "No goal."}${swing}`,
      color: club.primary,
    },
  });

  beats.sort((p, q) => p.t - q.t);
  const tags = [shot.player, shot.creator, shot.defender].filter((id): id is string => !!id);
  return { start, end, beats, goalEnd: goalX > 0 ? 1 : -1, tags };
}
