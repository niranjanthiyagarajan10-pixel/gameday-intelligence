import type { BeatDraw, Clip, Explanation, Roster, Shot } from "../types";
import type { Spot } from "./overlays";

/** What the Live tab hands the 3D pitch to explain one shot. */
export interface ExplainRequest {
  key: string;
  title: string; // the moment's kind label, e.g. "Goal" or "Big chance"
  shot: Shot;
  clip: Clip;
  story?: Explanation; // the Explainer's verified beats: the replay freezes on each one
  lang?: string;
  voice?: boolean; // a voice reads each beat and releases the hold when it ends
}

export interface Caption {
  kind: string;
  text: string;
  color: string;
  step?: number; // the story beat it belongs to; -1 for why it worked
}

export type Draw =
  | { type: "arrow"; a: Spot; b: Spot; color: string; width: number; opacity: number }
  | { type: "line"; a: Spot; b: Spot; color: string; width: number; opacity: number }
  | { type: "ring"; at: Spot; color: string; radius: number }
  | { type: "zone"; at: Spot; color: string; radius: number }
  | { type: "wedge"; apex: Spot; a: Spot; b: Spot; color: string };

export interface Beat {
  t: number; // match time in seconds
  caption?: Caption;
  draw?: Draw[];
  rate?: number; // playback speed from here on
  cam?: "shooter";
  strike?: boolean; // the ball is struck: draw its flight
  hold?: number; // freeze the replay here for up to this many ms (a voice can release it sooner)
}

export interface Script {
  start: number;
  end: number;
  beats: Beat[];
  goalEnd: 1 | -1; // which end the shot was aimed at, in world X sign
  tags: string[]; // players who get a name tag during the replay
}

const BEFORE_S = 8;
const AFTER_S = 3;
const SLOW_FROM_S = 1.0;
const GOAL_POSTS: [number, number] = [30.34, 37.66];

const OUTCOME: Record<string, string> = {
  goal: "Goal.",
  saved: "Saved by the keeper.",
  off_target: "Off target.",
  blocked: "Blocked.",
};

const pct = (p: number) => Math.round(p * 100);

/**
 * The telestrated replay of one shot, as timed beats. Every number and name in a caption is filled
 * here from the engine's shot record and roster. Nothing is generated by a model.
 */
export function buildScript(req: ExplainRequest, roster: Roster, signal: string): Script | null {
  if (req.story && req.story.beats.length) return storyScript(req, req.story, roster, signal);
  const { shot, clip } = req;
  const frames = clip.frames;
  if (frames.length < 2) return null;
  const start = Math.max(frames[0].t, shot.t - BEFORE_S);
  const end = Math.min(frames[frames.length - 1].t, shot.t + AFTER_S);
  const club = roster.clubs[shot.team];
  const name = (id: string | null | undefined) => (id ? roster.players[id]?.name ?? id : "");
  const shooter = name(shot.player);
  const goalX = shot.team === "home" ? 105 : 0; // home always attacks toward x = 105 (engine/pitch.py)
  const beats: Beat[] = [];

  beats.push({
    t: start,
    rate: 1,
    caption: { kind: `Replay · ${shot.minute}'`, text: `${req.title} for ${club.name}. Watch how ${shooter} got the chance.`, color: club.primary },
  });

  // The build-up: each pass by the attacking side as it is played.
  const passes = clip.events.filter((e) => e.type === "pass" && e.team === shot.team && e.t >= start && e.t <= shot.t && e.end_x !== null && e.end_y !== null);
  for (const e of passes) {
    const ok = e.outcome === "complete";
    beats.push({
      t: e.t,
      draw: [{ type: "arrow", a: { x: e.x, y: e.y }, b: { x: e.end_x!, y: e.end_y! }, color: ok ? club.primary : "#f4f4f1", width: ok ? 0.32 : 0.18, opacity: ok ? 0.85 : 0.4 }],
    });
  }
  const assist = [...passes].reverse().find((e) => e.player === shot.creator);
  if (shot.creator && assist) {
    beats.push({
      t: assist.t,
      caption: { kind: "The pass", text: `${name(shot.creator)} picks out ${shooter}.`, color: club.primary },
      draw: [{ type: "ring", at: shot.creator, color: "#f4f4f1", radius: 2.4 }],
    });
  }

  // The moment of the shot, slowed down: where it was taken from and who was close.
  const setUp: Draw[] = [
    { type: "wedge", apex: shot.player, a: { x: goalX, y: GOAL_POSTS[0] }, b: { x: goalX, y: GOAL_POSTS[1] }, color: signal },
    { type: "ring", at: shot.player, color: signal, radius: 2.6 },
  ];
  let defence = "";
  if (shot.defender && shot.defender_m !== null) {
    setUp.push({ type: "ring", at: shot.defender, color: "#f4f4f1", radius: 2.4 });
    setUp.push({ type: "line", a: shot.player, b: shot.defender, color: "#f4f4f1", width: 0.14, opacity: 0.7 });
    defence = ` Nearest defender ${name(shot.defender)} is ${shot.defender_m.toFixed(1)} m away.`;
  }
  beats.push({
    t: Math.max(start, shot.t - SLOW_FROM_S),
    rate: 0.3,
    cam: "shooter",
    draw: setUp,
    caption: {
      kind: "The shot",
      text: `${shooter} shoots from ${shot.distance_m.toFixed(1)} m, with ${Math.round(shot.angle_deg)} degrees of goal to aim at.${defence}`,
      color: club.primary,
    },
  });
  beats.push({
    t: shot.t,
    rate: 0.45,
    strike: true,
    caption: {
      kind: `xG ${shot.xg.toFixed(2)}`,
      text: `A chance like this is scored about ${pct(shot.xg)} times in 100.`,
      color: club.primary,
    },
  });

  const goal = shot.outcome === "goal";
  const [h, a] = shot.score_before.split("-").map(Number);
  const after = goal ? (shot.team === "home" ? `${h + 1}-${a}` : `${h}-${a + 1}`) : shot.score_before;
  const [ifGoal, ifMiss] = [pct(shot.wp_if_goal), pct(shot.wp_if_miss)];
  let swing: string;
  if (goal) {
    swing = ifGoal === ifMiss
      ? ` Win probability for ${club.name}: ${ifGoal}%, the same as if it had missed.`
      : ` Win probability for ${club.name} rises to ${ifGoal}%, from ${ifMiss}% had it missed.`;
  } else {
    swing = ifGoal === ifMiss
      ? ` Win probability for ${club.name} stays at ${ifMiss}%. A goal would have moved it by less than one point.`
      : ` A goal would have lifted ${club.name}'s win probability to ${ifGoal}%. It stays at ${ifMiss}%.`;
  }
  beats.push({
    t: Math.min(end, shot.t + 0.9),
    rate: 1,
    caption: {
      kind: goal ? `Goal · ${roster.clubs.home.short} ${after.replace("-", " : ")} ${roster.clubs.away.short}` : "Outcome",
      text: `${OUTCOME[shot.outcome] ?? "No goal."}${swing}`,
      color: club.primary,
    },
  });

  beats.sort((p, q) => p.t - q.t);
  const tags = [shot.player, shot.creator, shot.defender].filter((id): id is string => !!id);
  return { start, end, beats, goalEnd: goalX > 0 ? 1 : -1, tags };
}

const STEP_TITLE: Record<string, string> = {
  won: "Ball won",
  foul_won: "Foul won",
  restart: "Set piece",
  pass: "The pass",
  carry: "The run",
  tackle_beaten: "Tackle beaten",
  shot: "The shot",
};

export const OUTCOME_TITLE: Record<string, string> = { goal: "Goal", saved: "Saved", blocked: "Blocked", off_target: "Off target" };

/** How long a caption holds when no voice reads it: long enough to read it twice over. */
const readMs = (text: string) => Math.min(9000, 1200 + text.length * 55);
const GAP_S = 4; // a gap longer than this between beats plays fast
const FAST_RATE = 4;
const VOICE_HOLD_MS = 14000; // with a voice, the hold ends when the line has been said

function storyDraw(d: BeatDraw, color: string, signal: string, goal: [Spot, Spot], shooter: string): Draw[] {
  if ("arrow" in d) {
    const [x, y, ex, ey] = d.arrow;
    return [{ type: "arrow", a: { x, y }, b: { x: ex, y: ey }, color, width: 0.36, opacity: 0.92 }];
  }
  if ("run" in d) {
    const [x, y, ex, ey] = d.run;
    return [{ type: "arrow", a: { x, y }, b: { x: ex, y: ey }, color: "#f4f4f1", width: 0.2, opacity: 0.75 }];
  }
  if ("ring" in d) {
    if (!d.ring) return [];
    return [d.tone === "beaten"
      ? { type: "ring", at: d.ring, color: "#f4f4f1", radius: 1.5 }
      : { type: "ring", at: d.ring, color: signal, radius: 2.4 }];
  }
  if ("spot" in d) return [{ type: "ring", at: { x: d.spot[0], y: d.spot[1] }, color: signal, radius: 1.2 }];
  if ("shot" in d) return [{ type: "wedge", apex: shooter, a: goal[0], b: goal[1], color: signal }];
  return [{ type: "zone", at: d.space, color: signal, radius: d.radius_m }];
}

/**
 * The replay as the Explainer tells it: it plays the move and freezes on each beat while its verified
 * line is shown and read, then ends on why it worked. The lines come from the server already checked;
 * the rest of the text here is labels.
 */
function storyScript(req: ExplainRequest, story: Explanation, roster: Roster, signal: string): Script | null {
  const { shot, clip } = req;
  const frames = clip.frames;
  if (frames.length < 2) return null;
  const club = roster.clubs[shot.team];
  const written = req.lang && req.lang !== "en" ? story.langs[req.lang] : undefined;
  const lines = written?.lines ?? story.beats.map((b) => b.line);
  const why = written?.why ?? story.why;
  const hold = (text: string) => (req.voice ? VOICE_HOLD_MS : readMs(text));
  const first = frames[0].t;
  const start = Math.max(first, Math.min(story.beats[0].t - 1.5, shot.t - 6));
  const end = Math.min(frames[frames.length - 1].t, shot.t + AFTER_S);
  const goalX = shot.team === "home" ? 105 : 0;
  const goal: [Spot, Spot] = [{ x: goalX, y: GOAL_POSTS[0] }, { x: goalX, y: GOAL_POSTS[1] }];
  const beats: Beat[] = [{ t: start, rate: 1 }];

  story.beats.forEach((b, i) => {
    // A move that started before the clip (a foul, then a free kick) shows its first beat at the clip's start.
    const isShot = b.kind === "shot";
    const t = isShot ? Math.max(start + 0.2, shot.t - SLOW_FROM_S) : Math.min(Math.max(b.t, start + 0.2), shot.t - SLOW_FROM_S - 0.1);
    const title = b.key ? "Key pass" : STEP_TITLE[b.kind] ?? "The move";
    beats.push({
      t,
      rate: isShot ? 0.3 : 1,
      cam: isShot ? "shooter" : undefined,
      hold: hold(lines[i] ?? b.line),
      draw: b.draw.flatMap((d) => storyDraw(d, club.primary, signal, goal, shot.player)),
      caption: { kind: `${i + 1} / ${story.beats.length} · ${title}`, text: lines[i] ?? b.line, color: club.primary, step: i },
    });
  });
  // Quiet spells in the move (a free kick being set up, a long spell of passing) play fast.
  const marks = beats.map((b) => b.t).sort((p, q) => p - q);
  for (let i = 0; i < marks.length - 1; i++) {
    if (marks[i + 1] - marks[i] > GAP_S) beats.push({ t: marks[i] + 0.8, rate: FAST_RATE });
  }
  beats.push({ t: shot.t, rate: 0.45, strike: true });
  beats.push({
    t: Math.min(end, shot.t + 0.9),
    rate: 1,
    hold: hold(why),
    caption: { kind: `${OUTCOME_TITLE[shot.outcome] ?? "Outcome"} · ${shot.outcome === "goal" ? "Why it worked" : "The verdict"}`, text: why, color: club.primary, step: -1 },
  });
  beats.sort((p, q) => p.t - q.t);
  const tags = [...new Set(story.beats.flatMap((b) => [b.player, b.to]).filter((id): id is string => !!id))];
  return { start, end, beats, goalEnd: goalX > 0 ? 1 : -1, tags };
}
